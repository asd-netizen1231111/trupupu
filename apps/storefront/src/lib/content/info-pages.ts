/**
 * Тексты информационных страниц.
 * Сейчас это ЗАГЛУШКИ — заменим реальным текстом позже.
 * Каждый абзац — отдельная строка в массиве `paragraphs`.
 */
/**
 * Разметка внутри текста: **жирный**, [текст](https://ссылка).
 */
export type InfoBlock =
  | { type: "p"; text: string }
  | { type: "ul"; items: string[] }
  /** Нумерованный список; номер пункта = prefix + (start + индекс), напр. «2.1.» */
  | { type: "ol"; items: string[]; prefix?: string; start?: number }
  | { type: "h3"; text: string }
  | { type: "note"; text: string }

export type InfoSection = {
  heading?: string
  paragraphs: string[]
  /** Дополнительные блоки (подзаголовки h3, списки, примечания) после абзацев */
  blocks?: InfoBlock[]
}

export type InfoPage = {
  slug: string
  title: string
  /** Подзаголовок документа под h1 */
  subtitle?: string
  description: string // для SEO (meta description)
  /** Дата последнего обновления — выводится в самом верху страницы */
  updatedAt?: string
  /** Вводный абзац под заголовком */
  intro?: string
  /** Заключительная строка внизу страницы */
  outro?: string
  /** Показывать оглавление по заголовкам разделов */
  toc?: boolean
  sections: InfoSection[]
}

